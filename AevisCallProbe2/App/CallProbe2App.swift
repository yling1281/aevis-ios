import SwiftUI

/// ## 通话二探针 —— 回答第一颗探针**没能回答**的那个问题
///
/// ## 第一颗探针答了什么、没答什么
///
/// `AevisCallProbe` 证明了：**一个纯净的小包**（`com.aevis.callprobe`，
/// 只有一个可执行文件、不嵌任何扩展、`deploymentTarget 17.4`）
/// **装得上，但系统界面弹不出来**。
///
/// 它**没能**回答的是：这个"弹不出来"到底是因为
///   (a) 全能签重签用的描述文件里**真的没有**通话资格（`aps-environment`），
///   还是 (b) 探针和主 App 之间有**结构差异**，差异本身导致了失败。
///
/// 主 App 跟第一颗探针有三处不一样（2026-10-01 逐项比对出来的）：
///
/// | # | 主 App | 第一颗探针 | 是不是嫌疑 |
/// |---|---|---|---|
/// | 1 | **嵌了 `AevisBroadcast.appex`** | 一个可执行文件 | 🔴 最大嫌疑 |
/// | 2 | `deploymentTarget 17.0` | `17.4` | ⚠️ 存疑 |
/// | 3 | 一堆音频/QQ 保活一起启动 | 干净启动 | ⚠️ 存疑 |
///
/// ## 这颗探针怎么把这三种可能一次分开
///
/// 它按**主 App 的方式**来（所以第 2、3 条自动对齐）：
///   · `deploymentTarget = 17.4`（跟主 App 的运行时行为一致）
///   · 启动时**先抢一次音频会话**（模拟主 App 的 `AudioSession` / QQ 保活），
///     再拨号 —— 如果"有人占着音频会话"是原因，这里就会复现
///
/// 并且它**故意嵌一个假的扩展**（`AevisCallProbe2Ext.appex`）：
///   · **嵌了还不弹** ⇒ 元凶是**扩展**（签名要管两个 bundle，资格没传下去）
///   · **摘了才弹**   ⇒ 同上，而且我们能立刻给主 App 一个"摘扩展"的版本
///   · **摘了也不弹** ⇒ 跟结构无关，**是描述文件本身没资格**（回到原结论）
///
/// ⚠️ 这颗探针**不接真实通话**（3 秒自动挂断），和第一颗一样。
/// 它只回答"界面弹不弹" + "摘了扩展弹不弹"。
@main
struct CallProbe2App: App {
    // ⚠️ 用 `shared` 而不是 `()` —— 理由和第一颗探针完全相同
    //    （主 actor 隔离的初始化器不能在 App.init 里调）。
    @StateObject private var model = CallProbe2Model.shared

    var body: some Scene {
        WindowGroup {
            CallProbe2View().environmentObject(model)
        }
    }
}
