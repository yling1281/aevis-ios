    /// 「帮助」的内容 —— 指令列表。
    ///
    /// 用户明确要：@ 它但说的指令不对，就把这一坨发出来。
    /// 所以它得短、一眼扫得完。
    static var help: String {
        var lines = ["我是 Aevis 的客服机器人，回下面这些词就行：", ""]
        for command in all where command.title != "看指令" {
            lines.append("· " + command.keys.prefix(2).joined(separator: " / "))
        }
        lines.append("")
        lines.append("直接回一个词就行（比如「售后」「怎么买」）。")
        lines.append("要我聊天的话，得在 App 里打开，这里我只管回答问题。")
        return lines.joined(separator: "\n")
    }

    /// 拿一句话去撞指令表。撞上就回文案，撞不上返回 nil。
    ///
    /// 匹配规则很土：用户那句话里包含某个触发词就算命中。
    /// 客服场景够用了 —— 真要精确匹配，用户说「我想知道怎么买呀」
    /// 反而会匹配不上，那才是灾难。
    static func reply(to raw: String) -> String? {
        let text = raw
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
        guard !text.isEmpty else { return nil }

        // 长的触发词优先 —— 否则「注册码」会被「码」这种短词抢走
        var candidates: [(word: String, command: Command)] = []
        for command in all {
            for key in command.keys {
                candidates.append((key.lowercased(), command))
            }
        }
        candidates.sort { $0.word.count > $1.word.count }

        for candidate in candidates where text.contains(candidate.word) {
            return candidate.command.body
        }
        return nil
    }

